import { PrintColumn, PrintTotals } from '../utils/print-format.util';

export type PdfFormat = 'a4' | 'a5';
export type PdfOrientation = 'portrait' | 'landscape';

/** Semantic colour of a value (amount owed, paid, status…). */
export type PdfTone = 'default' | 'accent' | 'positive' | 'negative' | 'warning';

// ─────────────────────────────────────────────────────────────────
//  Layout — what the pagination engine consumes
// ─────────────────────────────────────────────────────────────────

/**
 * A document described as a flow of blocks. The engine pours the blocks
 * onto fixed-size pages: blocks never split, tables split between rows and
 * repeat their header on every page.
 *
 * All HTML here is generated by templates from escaped data — never pass
 * user input through unescaped.
 */
export interface PdfLayout {
  readonly format: PdfFormat;
  readonly orientation: PdfOrientation;
  /** Template-specific stylesheet, applied on top of the base theme. */
  readonly css?: string;
  /** Compact bar shown at the top of every page except the first. */
  readonly runningHeader?: string;
  /**
   * Shown at the bottom of every page. `{{page}}` and `{{pages}}` are
   * replaced with the page number and the total page count.
   */
  readonly footer?: string;
  readonly blocks: ReadonlyArray<PdfBlock>;
}

export type PdfBlock = PdfHtmlBlock | PdfTableBlock;

/** An unbreakable chunk of content (a card, a heading, a receipt…). */
export interface PdfHtmlBlock {
  readonly kind: 'html';
  readonly html: string;
  /** Always start this block on a fresh page. */
  readonly pageBreakBefore?: boolean;
}

/** A table that may span pages; it splits between rows only. */
export interface PdfTableBlock {
  readonly kind: 'table';
  /** Heading kept on the same page as the table's first rows. */
  readonly caption?: string;
  /** `<colgroup>` markup — fixes column widths identically on every page. */
  readonly colgroup?: string;
  /** Header row markup (`<tr>…</tr>`), repeated on every page. */
  readonly head: string;
  /** One `<tr>…</tr>` per row. */
  readonly rows: ReadonlyArray<string>;
  /** Totals rows, kept together and never left on a page without data rows. */
  readonly foot?: ReadonlyArray<string>;
  /** Row shown when `rows` is empty. */
  readonly emptyRow?: string;
  readonly pageBreakBefore?: boolean;
}

// ─────────────────────────────────────────────────────────────────
//  Report — the generic business document template
// ─────────────────────────────────────────────────────────────────

export interface PdfField {
  readonly label: string;
  readonly value: string;
}

export interface PdfMetric {
  readonly label: string;
  readonly value: string;
  readonly tone?: PdfTone;
  /** Visually dominant (e.g. the grand total). */
  readonly emphasis?: boolean;
}

export interface PdfReportTable<T> {
  readonly caption?: string;
  readonly columns: ReadonlyArray<PrintColumn<T>>;
  readonly rows: ReadonlyArray<T>;
  readonly totals?: PrintTotals;
  readonly emptyMessage?: string;
}

/**
 * A statement / invoice style document: brand header, party details, key
 * figures, a data table, a totals box, notes and signature lines. Every
 * section is optional.
 */
export interface PdfReport<T = unknown> {
  /** Document type, e.g. "كشف حساب المورد" / "فاتورة مشتريات". */
  readonly title: string;
  /** Usually the party name. */
  readonly subtitle?: string;
  /** Document number shown under the title, e.g. the invoice number. */
  readonly reference?: string;
  readonly status?: { readonly label: string; readonly tone: PdfTone };
  readonly orientation?: PdfOrientation;
  readonly fields?: ReadonlyArray<PdfField>;
  readonly metrics?: ReadonlyArray<PdfMetric>;
  readonly table?: PdfReportTable<T>;
  /** Right-aligned totals box under the table (invoice style). */
  readonly totals?: ReadonlyArray<PdfMetric>;
  readonly notes?: string;
  readonly signatures?: ReadonlyArray<string>;
}
